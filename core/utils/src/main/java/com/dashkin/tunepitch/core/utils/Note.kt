package com.dashkin.tunepitch.core.utils

// Represents one of the 12 musical notes within an octave,
// following standard Western music notation (C to B).
enum class Note(val displayName: String) {
    C("C"),
    C_SHARP("C#"),
    D("D"),
    D_SHARP("D#"),
    E("E"),
    F("F"),
    F_SHARP("F#"),
    G("G"),
    G_SHARP("G#"),
    A("A"),
    A_SHARP("A#"),
    B("B")
}
